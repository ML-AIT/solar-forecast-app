"""Generate lib/thailandMap.ts from Natural Earth country outlines.

The map on the overview page is plain SVG, so we pre-project the outlines once and commit the result.
Run this only when the projection or the source data changes:

    curl -sSL -o ne50.geojson \
      https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_50m_admin_0_countries.geojson
    python scripts/gen_thailand_map.py ne50.geojson > lib/thailandMap.ts

Natural Earth data is public domain (https://www.naturalearthdata.com/about/terms-of-use/).
"""

import json
import math
import sys

# Map window (degrees). Must match MAP_PROJECTION in the generated file.
LON_MIN, LON_MAX = 97.0, 106.0
LAT_MIN, LAT_MAX = 5.4, 20.7
WIDTH = 400.0
# Equirectangular with the x axis shrunk by cos(mid-latitude), so Thailand keeps its shape.
X_FACTOR = math.cos(math.radians((LAT_MIN + LAT_MAX) / 2))
SCALE = WIDTH / ((LON_MAX - LON_MIN) * X_FACTOR)
HEIGHT = round((LAT_MAX - LAT_MIN) * SCALE)
TOLERANCE_PX = 0.6

NEIGHBOURS = {"MMR", "LAO", "KHM", "MYS", "VNM"}


def project(lon: float, lat: float) -> tuple[float, float]:
    return ((lon - LON_MIN) * X_FACTOR * SCALE, (LAT_MAX - lat) * SCALE)


def simplify(points: list[tuple[float, float]], tol: float) -> list[tuple[float, float]]:
    """Douglas-Peucker line simplification."""
    if len(points) < 3:
        return points
    (x1, y1), (x2, y2) = points[0], points[-1]
    dx, dy = x2 - x1, y2 - y1
    norm = math.hypot(dx, dy)
    best, idx = 0.0, 0
    for i in range(1, len(points) - 1):
        px, py = points[i]
        if norm == 0:  # closed ring: measure distance to the shared end point
            d = math.hypot(px - x1, py - y1)
        else:
            d = abs(dy * px - dx * py + x2 * y1 - y2 * x1) / norm
        if d > best:
            best, idx = d, i
    if best <= tol:
        return [points[0], points[-1]]
    return simplify(points[: idx + 1], tol)[:-1] + simplify(points[idx:], tol)


def rings(geometry: dict) -> list[list[list[float]]]:
    if geometry["type"] == "Polygon":
        return geometry["coordinates"]
    return [ring for poly in geometry["coordinates"] for ring in poly]


def ring_in_window(ring: list[list[float]]) -> bool:
    lons = [p[0] for p in ring]
    lats = [p[1] for p in ring]
    return not (
        max(lons) < LON_MIN - 1 or min(lons) > LON_MAX + 1
        or max(lats) < LAT_MIN - 1 or min(lats) > LAT_MAX + 1
    )


def to_path(ring_list: list[list[list[float]]]) -> str:
    parts = []
    for ring in ring_list:
        if not ring_in_window(ring):
            continue
        pts = simplify([project(lon, lat) for lon, lat in ring], TOLERANCE_PX)
        if len(pts) < 4:
            continue
        coords = " ".join(f"{x:.1f},{y:.1f}" for x, y in pts[:-1])
        parts.append(f"M{coords}Z")
    return "".join(parts)


def main() -> None:
    with open(sys.argv[1], encoding="utf-8") as f:
        data = json.load(f)
    thailand: list = []
    neighbours: list = []
    for feat in data["features"]:
        code = feat["properties"].get("ADM0_A3")
        if code == "THA":
            thailand += rings(feat["geometry"])
        elif code in NEIGHBOURS:
            neighbours += rings(feat["geometry"])

    out = f"""// Generated by scripts/gen_thailand_map.py. Do not edit by hand.
// Outlines: Natural Earth 1:50m admin-0 countries v5.1.2 (public domain).

export const MAP_WIDTH = {WIDTH:.0f};
export const MAP_HEIGHT = {HEIGHT};

const LON_MIN = {LON_MIN};
const LAT_MAX = {LAT_MAX};
const X_FACTOR = {X_FACTOR:.6f};
const SCALE = {SCALE:.6f};

/** Project a WGS84 point to map (SVG) coordinates. */
export function projectToMap(lon: number, lat: number): {{ x: number; y: number }} {{
  return {{ x: (lon - LON_MIN) * X_FACTOR * SCALE, y: (LAT_MAX - lat) * SCALE }};
}}

export const THAILAND_PATH =
  "{to_path(thailand)}";

export const NEIGHBOURS_PATH =
  "{to_path(neighbours)}";
"""
    sys.stdout.write(out)


if __name__ == "__main__":
    main()
